def build_wide_comparison(milp_rows: Sequence[dict], fcfs_by_traffic: Dict[str, dict]) -> List[dict]:
    grouped: Dict[Tuple[str, int], Dict[bool, dict]] = {}
    for row in milp_rows:
        grouped.setdefault((row["traffic_label"], int(row["radius_m"])), {})[bool(row["fair"])] = row

    out = []
    for (label, radius), pair in sorted(grouped.items(), key=lambda kv: (kv[0][0], kv[0][1])):
        nf = pair.get(False, {})
        fr = pair.get(True, {})
        fcfs = fcfs_by_traffic[label]
        out.append({
            "traffic_label": label,
            "lambda_x": nf.get("lambda_x", fr.get("lambda_x")),
            "lambda_y": nf.get("lambda_y", fr.get("lambda_y")),
            "lambda_total": nf.get("lambda_total", fr.get("lambda_total")),
            "radius_m": radius,
            "common_agent_count": nf.get("common_agent_count", fr.get("common_agent_count")),
            "milp_nofair_mean_delay_s": nf.get("mean_delay_s"),
            "milp_fair_mean_delay_s": fr.get("mean_delay_s"),
            "milp_nofair_p95_delay_s": nf.get("p95_delay_s"),
            "milp_fair_p95_delay_s": fr.get("p95_delay_s"),
            "milp_nofair_max_delay_s": nf.get("max_delay_s"),
            "milp_fair_max_delay_s": fr.get("max_delay_s"),
            "fcfs_mean_virtual_wait_s": fcfs.get("mean_delay_s"),
            "fcfs_p95_virtual_wait_s": fcfs.get("p95_delay_s"),
            "fcfs_theoretical_mg1_mean_wait_s": fcfs.get("theoretical_mg1_mean_wait_s"),
            "nofair_mean_solver_runtime_s": nf.get("solver_runtime_s_mean"),
            "fair_mean_solver_runtime_s": fr.get("solver_runtime_s_mean"),
            "nofair_p95_solver_runtime_s": nf.get("solver_runtime_s_p95"),
            "fair_p95_solver_runtime_s": fr.get("solver_runtime_s_p95"),
            "nofair_max_solver_runtime_s": nf.get("solver_runtime_s_max"),
            "fair_max_solver_runtime_s": fr.get("solver_runtime_s_max"),
            "nofair_total_solver_runtime_s": nf.get("solver_runtime_s_total"),
            "fair_total_solver_runtime_s": fr.get("solver_runtime_s_total"),
            "nofair_mean_model_rows": nf.get("model_rows_mean"),
            "fair_mean_model_rows": fr.get("model_rows_mean"),
            "nofair_mean_model_columns": nf.get("model_columns_mean"),
            "fair_mean_model_columns": fr.get("model_columns_mean"),
            "nofair_mean_original_binary_vars": nf.get("original_binary_vars_mean"),
            "fair_mean_original_binary_vars": fr.get("original_binary_vars_mean"),
            "nofair_mean_presolved_binary_vars": nf.get("presolved_binary_vars_mean"),
            "fair_mean_presolved_binary_vars": fr.get("presolved_binary_vars_mean"),
        })
    return out


def main() -> None:
    start = time.perf_counter()
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)

    parameter_rows = [
        {"parameter": "seed", "value": SEED, "note": "single seed study"},
        {"parameter": "radii_m", "value": ",".join(map(str, RADII)), "note": "nine radii"},
        {"parameter": "I_value", "value": I_VALUE, "note": "all selected folders use I_4"},
        {"parameter": "safe_distance_m", "value": D_SAFE, "note": "same-lane d_safe"},
        {"parameter": "cross_flow_separation_m", "value": D_SEP, "note": "I_4 / cross-flow center buffer"},
        {"parameter": "dt_s", "value": DT, "note": "simulation time step"},
        {"parameter": "horizon_N", "value": HORIZON, "note": "MILP prediction horizon"},
        {"parameter": "source_nominal_speed_mps", "value": V_NOMINAL, "note": "traffic generation speed"},
        {"parameter": "u_min_mps2", "value": U_MIN, "note": "control lower bound"},
        {"parameter": "u_max_mps2", "value": U_MAX, "note": "control upper bound"},
        {"parameter": "total_iterations", "value": TOTAL_ITERATIONS, "note": "finite experiment horizon"},
        {"parameter": "stop_add", "value": STOP_ADD, "note": "0: arrivals generated through the whole horizon"},
        {"parameter": "source_x_m", "value": SOURCE_X, "note": "X source"},
        {"parameter": "source_y_m", "value": SOURCE_Y, "note": "Y source"},
        {"parameter": "base_variables_per_active_agent", "value": 12 * HORIZON, "note": "s:4N + u:2N + w:4N + v:2N before pair/fairness auxiliaries"},
        {"parameter": "problem_size_source_of_truth", "value": "Gurobi logs", "note": "report original + presolved rows/columns/variable types"},
        {"parameter": "FCFS_baseline", "value": "one radius-independent event/virtual-wait FCFS per traffic", "note": "strict ascending global UID"},
        {"parameter": "missing_trajectory_policy", "value": "allow", "note": "retain solver/runtime metrics; leave MILP delay blank; common UID prefix uses available trajectories only"},
    ]
    for c in TRAFFIC_CASES:
        parameter_rows.append({
            "parameter": f"{c['label']}_roots",
            "value": f"False={c['false_root']} | True={c['true_root']}",
            "note": f"lambda_x=lambda_y={c['lambda_x']}",
        })
    write_csv(OUTPUT_ROOT / "parameters.csv", parameter_rows)

    runs = discover_all_runs()
    inventory_all: List[dict] = []
    milp_all: List[dict] = []
    fcfs_all: List[dict] = []
    common_all: List[dict] = []
    fcfs_by_traffic: Dict[str, dict] = {}

    for case in TRAFFIC_CASES:
        run_rows, fcfs_summary, common_summary, inventory_rows = analyze_traffic_case(case, runs)
        milp_all.extend(run_rows)
        fcfs_all.append(fcfs_summary)
        common_all.append(common_summary)
        inventory_all.extend(inventory_rows)
        fcfs_by_traffic[case["label"]] = fcfs_summary

        # Check source-code lambda/fairness against the explicit six-root mapping.
        for inv in inventory_rows:
            lx = inv.get("code_lambda_x")
            ly = inv.get("code_lambda_y")
            cf = inv.get("code_fair")
            if isinstance(lx, (int, float)) and abs(float(lx) - float(inv["lambda_x_expected"])) > 1e-12:
                print("WARNING lambda_x mismatch:", inv["source_code_file"], lx, inv["lambda_x_expected"])
            if isinstance(ly, (int, float)) and abs(float(ly) - float(inv["lambda_y_expected"])) > 1e-12:
                print("WARNING lambda_y mismatch:", inv["source_code_file"], ly, inv["lambda_y_expected"])
            if isinstance(cf, bool) and cf != bool(inv["fair"]):
                print("WARNING fair flag mismatch:", inv["source_code_file"], cf, inv["fair"])

    write_csv(OUTPUT_ROOT / "paper_summary.csv", milp_all)
    write_csv(OUTPUT_ROOT / "fcfs_summary.csv", fcfs_all)
    write_csv(OUTPUT_ROOT / "common_population_summary.csv", common_all)
    write_csv(OUTPUT_ROOT / "experiment_inventory.csv", inventory_all)

    wide = build_wide_comparison(milp_all, fcfs_by_traffic)
    write_csv(OUTPUT_ROOT / "paper_comparison_wide.csv", wide)

    master = {
        "created_by": Path(__file__).name,
        "output_root": str(OUTPUT_ROOT),
        "radii": RADII,
        "I_value": I_VALUE,
        "seed": SEED,
        "traffic_cases": TRAFFIC_CASES,
        "milp_run_count": len(milp_all),
        "fcfs_run_count": len(fcfs_all),
        "common_population": common_all,
        "fcfs_summary": fcfs_all,
        "analysis_wall_s": time.perf_counter() - start,
    }
    (OUTPUT_ROOT / "master_summary.json").write_text(
        json.dumps(master, indent=2, allow_nan=False, default=str), encoding="utf-8"
    )

    print("\n" + "=" * 80)
    print("POST-PROCESSING COMPLETE")
    print("=" * 80)
    print(f"Output root: {OUTPUT_ROOT}")
    print(f"MILP summary rows: {len(milp_all)} (expected 54 run folders; missing trajectory rows remain with blank delay)")
    print(f"FCFS summary rows: {len(fcfs_all)} (expected 3)")
    for row in common_all:
        print(
            f"  {row['traffic_label']}: common UID prefix N={row['common_complete_uid_prefix_N']}"
        )
    print("Main files:")
    print("  paper_summary.csv")
    print("  paper_comparison_wide.csv")
    print("  fcfs_summary.csv")
    print("  common_population_summary.csv")
    print("  experiment_inventory.csv")
    print("  master_summary.json")


if __name__ == "__main__":
    main()
