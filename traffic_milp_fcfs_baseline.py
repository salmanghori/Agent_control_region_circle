def parse_source_config(path: Optional[Path]) -> dict:
    if path is None or not path.exists():
        return {}
    text = path.read_text(encoding="utf-8", errors="ignore")
    out = {"source_code_file": str(path)}
    for key, rx in SOURCE_PATTERNS.items():
        m = rx.search(text)
        if not m:
            continue
        val = m.group(1)
        if val in {"True", "False"}:
            out[key] = val == "True"
        else:
            try:
                out[key] = int(val) if re.fullmatch(r"\d+", val) else float(val)
            except Exception:
                out[key] = val
    return out


