@dataclass
class UIDState:
    axis: str
    first_seen_time_s: Optional[float] = None
    previous: Optional[Tuple[float, float]] = None
    entry_time_s: Optional[float] = None
    center_time_s: Optional[float] = None
    exit_time_s: Optional[float] = None


def crossing_time(prev: Tuple[float, float], cur: Tuple[float, float], boundary: float) -> Optional[float]:
    t0, z0 = prev
    t1, z1 = cur
    if z1 < z0 - 1.0e-5:
        return None
    if abs(z0 - boundary) <= 1.0e-9:
        return t0
    if z0 <= boundary <= z1 and abs(z1 - z0) > EPS:
        a = (boundary - z0) / (z1 - z0)
        a = max(0.0, min(1.0, a))
        return t0 + a * (t1 - t0)
    return None


def trajectory_cache_path(rf: RunFiles) -> Path:
    base = OUTPUT_ROOT / "cache" / rf.key.traffic_label / ("fair" if rf.key.fair else "nofair")
    return base / f"R_{rf.key.radius}_trajectory_cache.json.gz"


def load_trajectory_cache(rf: RunFiles) -> Optional[Tuple[Dict[int, dict], dict]]:
    if rf.trajectory_file is None:
        return None
    if not USE_TRAJECTORY_CACHE:
        return None
    cp = trajectory_cache_path(rf)
    if not cp.exists():
        return None
    try:
        with gzip.open(cp, "rt", encoding="utf-8") as f:
            data = json.load(f)
        st = rf.trajectory_file.stat()
        meta = data.get("meta", {})
        if meta.get("source_size") != st.st_size or abs(meta.get("source_mtime", 0.0) - st.st_mtime) > 1e-6:
            return None
        rows = {int(k): v for k, v in data["rows"].items()}
        return rows, data["summary"]
    except Exception:
        return None


def save_trajectory_cache(rf: RunFiles, rows: Dict[int, dict], summary: dict) -> None:
    if rf.trajectory_file is None:
        return
    if not USE_TRAJECTORY_CACHE:
        return
    cp = trajectory_cache_path(rf)
    cp.parent.mkdir(parents=True, exist_ok=True)
    st = rf.trajectory_file.stat()
    payload = {
        "meta": {"source_size": st.st_size, "source_mtime": st.st_mtime, "source": str(rf.trajectory_file)},
        "summary": summary,
        "rows": {str(k): v for k, v in rows.items()},
    }
    with gzip.open(cp, "wt", encoding="utf-8") as f:
        json.dump(payload, f, separators=(",", ":"), allow_nan=False)


def parse_trajectory(rf: RunFiles) -> Tuple[Dict[int, dict], dict]:
    if rf.trajectory_file is None:
        raise FileNotFoundError(f"Trajectory JSON unavailable for {rf.week_dir}")
    cached = load_trajectory_cache(rf)
    if cached is not None:
        rows, summary = cached
        summary = dict(summary)
        summary["trajectory_cache_used"] = True
        return rows, summary

    radius = float(rf.key.radius)
    states: Dict[int, UIDState] = {}
    frame_count = 0
    record_count = 0
    nonmonotone = 0
    t0 = time.perf_counter()

    for frame_idx, frame in enumerate(iter_top_level_json_array(rf.trajectory_file)):
        frame_count += 1
        t = frame_idx * DT
        if not isinstance(frame, list):
            continue
        for rec in frame:
            if not isinstance(rec, (list, tuple)) or len(rec) < 6:
                continue
            record_count += 1
            x = scalar(rec[0])
            y = scalar(rec[1])
            axis = str(rec[4]).lower()
            uid = int(rec[5])
            if axis not in {"x", "y"}:
                continue
            z = x if axis == "x" else -y

            st = states.get(uid)
            if st is None:
                st = UIDState(axis=axis, first_seen_time_s=t)
                states[uid] = st
            elif st.axis != axis:
                raise ValueError(f"UID {uid} changes axis in {rf.trajectory_file}")

            if st.previous is not None:
                if z < st.previous[1] - 1.0e-5:
                    nonmonotone += 1
                if st.entry_time_s is None:
                    ct = crossing_time(st.previous, (t, z), -radius)
                    if ct is not None:
                        st.entry_time_s = ct
                if st.center_time_s is None:
                    ct = crossing_time(st.previous, (t, z), 0.0)
                    if ct is not None:
                        st.center_time_s = ct
                if st.exit_time_s is None:
                    ct = crossing_time(st.previous, (t, z), +radius)
                    if ct is not None:
                        st.exit_time_s = ct
            else:
                if abs(z + radius) <= 1.0e-7:
                    st.entry_time_s = t
                if abs(z) <= 1.0e-7:
                    st.center_time_s = t
                if abs(z - radius) <= 1.0e-7:
                    st.exit_time_s = t
            st.previous = (t, z)

        if frame_idx and frame_idx % 5000 == 0:
            print(f"    trajectory R={rf.key.radius} fair={rf.key.fair}: frame {frame_idx}")

    ideal = 2.0 * radius / V_NOMINAL
    rows: Dict[int, dict] = {}
    for uid, st in states.items():
        complete = st.entry_time_s is not None and st.exit_time_s is not None
        delay = None
        if complete:
            delay = float(st.exit_time_s - st.entry_time_s - ideal)
            if -1.0e-5 < delay < 0.0:
                delay = 0.0
        rows[uid] = {
            "uid": uid,
            "axis": st.axis,
            "first_seen_time_s": st.first_seen_time_s,
            "entry_time_s": st.entry_time_s,
            "center_time_s": st.center_time_s,
            "exit_time_s": st.exit_time_s,
            "delay_s": delay,
            "complete": complete,
        }

    summary = {
        "trajectory_file": str(rf.trajectory_file),
        "frame_count": frame_count,
        "record_count": record_count,
        "uids_seen": len(rows),
        "uids_completed": sum(1 for r in rows.values() if r["complete"]),
        "nonmonotone_sample_count": nonmonotone,
        "trajectory_parse_wall_s": time.perf_counter() - t0,
        "trajectory_cache_used": False,
    }
    save_trajectory_cache(rf, rows, summary)
    return rows, summary


def longest_complete_uid_prefix(rows: Dict[int, dict]) -> int:
    n = 0
    while True:
        uid = n + 1
        r = rows.get(uid)
        if r is None or not r.get("complete", False):
            return n
        n = uid


