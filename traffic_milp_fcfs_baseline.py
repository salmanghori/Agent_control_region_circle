def percentile(values: Sequence[float], q: float) -> Optional[float]:
    if not values:
        return None
    x = sorted(float(v) for v in values)
    if len(x) == 1:
        return x[0]
    p = q * (len(x) - 1)
    lo = int(math.floor(p))
    hi = int(math.ceil(p))
    if lo == hi:
        return x[lo]
    w = p - lo
    return x[lo] * (1.0 - w) + x[hi] * w


def stats(values: Sequence[float]) -> dict:
    x = [float(v) for v in values if v is not None and math.isfinite(float(v))]
    if not x:
        return {
            "count": 0,
            "mean": None,
            "median": None,
            "std": None,
            "p95": None,
            "max": None,
            "min": None,
            "total": 0.0,
        }
    return {
        "count": len(x),
        "mean": statistics.fmean(x),
        "median": statistics.median(x),
        "std": statistics.pstdev(x) if len(x) > 1 else 0.0,
        "p95": percentile(x, 0.95),
        "max": max(x),
        "min": min(x),
        "total": math.fsum(x),
    }


def write_csv(path: Path, rows: Sequence[dict], fieldnames: Optional[Sequence[str]] = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = list(rows)
    if fieldnames is None:
        fields: List[str] = []
        seen = set()
        for row in rows:
            for key in row:
                if key not in seen:
                    seen.add(key)
                    fields.append(key)
        fieldnames = fields
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(fieldnames), extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def write_csv_gz(path: Path, rows: Iterable[dict], fieldnames: Sequence[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(path, "wt", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(fieldnames), extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def latest_file(folder: Path, pattern: str) -> Optional[Path]:
    items = [p for p in folder.glob(pattern) if p.is_file()]
    return max(items, key=lambda p: p.stat().st_mtime) if items else None


def scalar(value) -> float:
    while isinstance(value, (list, tuple)):
        if not value:
            raise ValueError("Empty nested coordinate list")
        value = value[0]
    return float(value)


def json_load_maybe(path: Optional[Path]) -> dict:
    if path is None or not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except Exception as exc:
        return {"parse_error": str(exc)}


def iter_top_level_json_array(path: Path, chunk_size: int = 16 * 1024 * 1024) -> Iterator[object]:
    """Stream items from a top-level JSON array using only Python stdlib."""
    decoder = json.JSONDecoder()
    with path.open("r", encoding="utf-8") as f:
        buf = ""
        pos = 0
        started = False
        eof = False
        while True:
            if not eof and (pos >= len(buf) or len(buf) - pos < chunk_size // 4):
                rem = buf[pos:]
                chunk = f.read(chunk_size)
                eof = chunk == ""
                buf = rem + chunk
                pos = 0

            while pos < len(buf) and buf[pos].isspace():
                pos += 1

            if not started:
                if pos >= len(buf):
                    if eof:
                        raise ValueError(f"Empty JSON file: {path}")
                    continue
                if buf[pos] != "[":
                    raise ValueError(f"Expected top-level JSON array: {path}")
                pos += 1
                started = True

            while pos < len(buf) and (buf[pos].isspace() or buf[pos] == ","):
                pos += 1
            if pos < len(buf) and buf[pos] == "]":
                return
            if pos >= len(buf):
                if eof:
                    raise ValueError(f"Unexpected EOF in {path}")
                continue

            try:
                item, end = decoder.raw_decode(buf, pos)
            except json.JSONDecodeError:
                if eof:
                    raise
                rem = buf[pos:]
                chunk = f.read(chunk_size)
                eof = chunk == ""
                buf = rem + chunk
                pos = 0
                continue

            yield item
            pos = end


