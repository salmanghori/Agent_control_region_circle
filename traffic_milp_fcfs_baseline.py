def analyze_traffic_case(case: dict, all_runs: Dict[RunKey, RunFiles]) -> Tuple[List[dict], dict, dict, List[dict]]:
    label = case["label"]
    case_out = OUTPUT_ROOT / label
    case_out.mkdir(parents=True, exist_ok=True)
    print("\n" + "=" * 80)
    print(f"TRAFFIC {label}: lambda_x=lambda_y={case['lambda_x']}")
    print("=" * 80)

    trajectory_data: Dict[Tuple[int, bool], Dict[int, dict]] = {}
    trajectory_summaries: Dict[Tuple[int, bool], dict] = {}
    run_rows: List[dict] = []
    inventory_rows: List[dict] = []
    missing_trajectory_runs: List[str] = []

    # Parse every trajectory that actually exists.  A missing trajectory does
    # not discard the experiment: Gurobi logs/runtime are still analyzed later.
    for radius in RADII:
        for fair in (False, True):
            key = RunKey(label, radius, fair)
            rf = all_runs[key]
            print(f"\n  R={radius}, fair={fair}")

            runtime_data = json_load_maybe(rf.runtime_file)
            source_cfg = parse_source_config(rf.source_code_file)
            trajectory_available = rf.trajectory_file is not None and rf.trajectory_file.exists()

            if trajectory_available:
                uid_rows, traj_summary = parse_trajectory(rf)
                trajectory_data[(radius, fair)] = uid_rows
                trajectory_summaries[(radius, fair)] = traj_summary
                prefix_n = longest_complete_uid_prefix(uid_rows)
            else:
                uid_rows = {}
                traj_summary = {
                    "trajectory_file": None,
                    "frame_count": None,
                    "record_count": None,
                    "uids_seen": None,
                    "uids_completed": None,
                    "nonmonotone_sample_count": None,
                    "trajectory_parse_wall_s": None,
                    "trajectory_cache_used": False,
                }
                prefix_n = None
                missing_trajectory_runs.append(f"R={radius},fair={fair}")
                print("    trajectory JSON MISSING -> delay unavailable; keeping solver/runtime analysis")

            inv = {
                "traffic_label": label,
                "lambda_x_expected": case["lambda_x"],
                "lambda_y_expected": case["lambda_y"],
                "radius_m": radius,
                "fair": fair,
                "root": str(rf.root),
                "week_dir": str(rf.week_dir),
                "trajectory_available": trajectory_available,
                "delay_available": trajectory_available,
                "trajectory_file": str(rf.trajectory_file) if rf.trajectory_file else None,
                "runtime_file": str(rf.runtime_file) if rf.runtime_file else None,
                "mip_json_file": str(rf.mip_json_file) if rf.mip_json_file else None,
                "source_code_file": str(rf.source_code_file) if rf.source_code_file else None,
                "step_token": rf.step_token,
                "I_value": rf.i_value,
                "safe_distance": rf.safe_distance,
                "horizon": rf.horizon,
                "uids_seen": traj_summary["uids_seen"],
                "uids_completed": traj_summary["uids_completed"],
                "complete_uid_prefix_N": prefix_n,
                "program_wall_runtime_s": runtime_data.get("Code execution time (seconds)"),
                "generated_agents_x": runtime_data.get("No. of agent along x"),
                "generated_agents_y": runtime_data.get("No. of agent along y"),
                **source_cfg,
            }
            inventory_rows.append(inv)

    if not trajectory_data:
        raise RuntimeError(f"No trajectory JSON is available for traffic {label}; delay/FCFS population cannot be defined")

    # Common population is based only on runs for which trajectory data exists.
    # Missing trajectories are never guessed or imputed.
    prefix_by_run = {k: longest_complete_uid_prefix(v) for k, v in trajectory_data.items()}
    common_n = min(prefix_by_run.values()) if prefix_by_run else 0
    if common_n <= 0:
        raise RuntimeError(f"No common complete UID prefix for traffic {label}")
    common_uids = list(range(1, common_n + 1))

    completed_sets = [
        {uid for uid, r in rows.items() if r.get("complete")}
        for rows in trajectory_data.values()
    ]
    intersection = set.intersection(*completed_sets) if completed_sets else set()
    prefix_set = set(common_uids)
    intersection_extra_count = len(intersection - prefix_set)
    prefix_missing_from_intersection = len(prefix_set - intersection)

    available_count = len(trajectory_data)
    expected_count = len(RADII) * 2
    print(f"\n  Common complete UID prefix over AVAILABLE trajectories: 1..{common_n} ({common_n} agents)")
    print(f"  Trajectory coverage: {available_count}/{expected_count} runs")
    if missing_trajectory_runs:
        print("  Missing trajectory runs (delay will be blank): " + ", ".join(missing_trajectory_runs))
    if intersection_extra_count:
        print(
            f"  NOTE: set intersection contains {intersection_extra_count} additional non-prefix UIDs; "
            "they are intentionally excluded to preserve one contiguous traffic sequence."
        )

    write_csv(case_out / "common_uids.csv", [{"uid": uid} for uid in common_uids])

    # Reference arrival sequence: prefer R=40, fair=False; otherwise use the
    # first available no-fair trajectory, then any available trajectory.
    ref_key = (40, False) if (40, False) in trajectory_data else None
    if ref_key is None:
        nofair_keys = sorted([k for k in trajectory_data if k[1] is False])
        ref_key = nofair_keys[0] if nofair_keys else sorted(trajectory_data)[0]
    ref_rows = trajectory_data[ref_key]

    arrivals = []
    source_time_max_diff = 0.0
    source_axis_mismatch_count = 0
    source_time_mismatch_count = 0
    for uid in common_uids:
        ref = ref_rows[uid]
        t_ref = float(ref["first_seen_time_s"])
        axis_ref = str(ref["axis"])
        for (radius, fair), rows in trajectory_data.items():
            rr = rows.get(uid)
            if rr is None or rr.get("first_seen_time_s") is None:
                source_time_mismatch_count += 1
                continue
            if str(rr["axis"]) != axis_ref:
                source_axis_mismatch_count += 1
            diff = abs(float(rr["first_seen_time_s"]) - t_ref)
            source_time_max_diff = max(source_time_max_diff, diff)
            if diff > DT + 1.0e-7:
                source_time_mismatch_count += 1
        arrivals.append({"uid": uid, "axis": axis_ref, "release_time_s": t_ref})

    fcfs_rows, fcfs_summary = run_event_fcfs(
        arrivals,
        lambda_x=float(case["lambda_x"]),
        lambda_y=float(case["lambda_y"]),
    )
    fcfs_summary.update({
        "traffic_label": label,
        "common_agent_count": common_n,
        "common_population_trajectory_run_count": available_count,
        "missing_trajectory_run_count": len(missing_trajectory_runs),
        "missing_trajectory_runs": ";".join(missing_trajectory_runs),
        "reference_run_for_arrivals": f"R={ref_key[0]}, fair={ref_key[1]}",
        "source_time_consistency_max_abs_s": source_time_max_diff,
        "source_time_mismatch_count": source_time_mismatch_count,
        "source_axis_mismatch_count": source_axis_mismatch_count,
    })
    write_csv(case_out / "fcfs_per_agent.csv", fcfs_rows)
    write_csv(case_out / "fcfs_summary.csv", [fcfs_summary])

    # MILP delay detail: write only runs with available trajectories.  Solver
    # summaries are still created for all 18 requested run folders.
    milp_agent_detail_path = case_out / "milp_common_agent_delays.csv.gz"
    detail_fields = [
        "traffic_label", "lambda_x", "lambda_y", "radius_m", "fair",
        "common_agent_count", "uid", "axis", "source_first_seen_time_s",
        "entry_time_s", "center_time_s", "exit_time_s", "delay_s",
    ]

    with gzip.open(milp_agent_detail_path, "wt", newline="", encoding="utf-8") as gf:
        detail_writer = csv.DictWriter(gf, fieldnames=detail_fields)
        detail_writer.writeheader()

        for radius in RADII:
            for fair in (False, True):
                rf = all_runs[RunKey(label, radius, fair)]
                data_key = (radius, fair)
                trajectory_available = data_key in trajectory_data

                if trajectory_available:
                    rows = trajectory_data[data_key]
                    delays = [float(rows[uid]["delay_s"]) for uid in common_uids]
                    ds = stats(delays)
                    for uid in common_uids:
                        rr = rows[uid]
                        detail_writer.writerow({
                            "traffic_label": label,
                            "lambda_x": case["lambda_x"],
                            "lambda_y": case["lambda_y"],
                            "radius_m": radius,
                            "fair": fair,
                            "common_agent_count": common_n,
                            "uid": uid,
                            "axis": rr["axis"],
                            "source_first_seen_time_s": rr["first_seen_time_s"],
                            "entry_time_s": rr["entry_time_s"],
                            "center_time_s": rr["center_time_s"],
                            "exit_time_s": rr["exit_time_s"],
                            "delay_s": rr["delay_s"],
                        })
                else:
                    ds = stats([])

                print(f"\n    solver analysis R={radius}, fair={fair}")
                solver_summary = parse_solver_run(rf)
                runtime_data = json_load_maybe(rf.runtime_file)
                program_wall = runtime_data.get("Code execution time (seconds)")
                solver_total = solver_summary.get("solver_runtime_s_total")
                solver_fraction = None
                if isinstance(program_wall, (int, float)) and program_wall > 0 and isinstance(solver_total, (int, float)):
                    solver_fraction = float(solver_total) / float(program_wall)

                traj_sum = trajectory_summaries.get(data_key, {})
                run_row = {
                    "traffic_label": label,
                    "lambda_x": case["lambda_x"],
                    "lambda_y": case["lambda_y"],
                    "lambda_total": float(case["lambda_x"]) + float(case["lambda_y"]),
                    "radius_m": radius,
                    "fair": fair,
                    "trajectory_available": trajectory_available,
                    "delay_available": trajectory_available,
                    "missing_trajectory_reason": None if trajectory_available else "vehicles_positions_id JSON missing",
                    "common_agent_count": common_n,
                    "common_population_trajectory_run_count": available_count,
                    "mean_delay_s": ds["mean"],
                    "median_delay_s": ds["median"],
                    "std_delay_s": ds["std"],
                    "p95_delay_s": ds["p95"],
                    "max_delay_s": ds["max"],
                    "total_delay_s": ds["total"] if trajectory_available else None,
                    "program_wall_runtime_s": program_wall,
                    "generated_agents_x": runtime_data.get("No. of agent along x"),
                    "generated_agents_y": runtime_data.get("No. of agent along y"),
                    "solver_runtime_fraction_of_program": solver_fraction,
                    "trajectory_uids_seen": traj_sum.get("uids_seen"),
                    "trajectory_uids_completed": traj_sum.get("uids_completed"),
                    "complete_uid_prefix_N_this_run": prefix_by_run.get(data_key),
                    "week_dir": str(rf.week_dir),
                    **solver_summary,
                }
                run_rows.append(run_row)

    prefix_values = list(prefix_by_run.values())
    common_summary = {
        "traffic_label": label,
        "lambda_x": case["lambda_x"],
        "lambda_y": case["lambda_y"],
        "lambda_total": float(case["lambda_x"]) + float(case["lambda_y"]),
        "common_complete_uid_prefix_N": common_n,
        "common_population_defined_over_available_trajectories": True,
        "available_trajectory_run_count": available_count,
        "expected_trajectory_run_count": expected_count,
        "missing_trajectory_run_count": len(missing_trajectory_runs),
        "missing_trajectory_runs": ";".join(missing_trajectory_runs),
        "set_intersection_completed_uid_count": len(intersection),
        "intersection_extra_nonprefix_uid_count": intersection_extra_count,
        "prefix_missing_from_intersection_count": prefix_missing_from_intersection,
        "source_time_consistency_max_abs_s": source_time_max_diff,
        "source_time_mismatch_count": source_time_mismatch_count,
        "source_axis_mismatch_count": source_axis_mismatch_count,
        "min_complete_prefix_over_available_runs": min(prefix_values),
        "max_complete_prefix_over_available_runs": max(prefix_values),
        "comparison_note": (
            "Runs without trajectory JSON are excluded only from delay/common-population computation. "
            "Their Gurobi problem-size/runtime metrics are retained. No delay is imputed."
        ),
    }

    write_csv(case_out / "run_summary.csv", run_rows)
    write_csv(case_out / "experiment_inventory.csv", inventory_rows)
    write_csv(case_out / "common_population_summary.csv", [common_summary])

    return run_rows, fcfs_summary, common_summary, inventory_rows


