def discover_one_run(case: dict, radius: int, fair: bool) -> RunFiles:
    root = Path(case["true_root"] if fair else case["false_root"])
    radius_dir = root / f"R_{radius}"
    if not radius_dir.is_dir():
        raise FileNotFoundError(f"Missing radius folder: {radius_dir}")

    matches: List[Tuple[Path, re.Match]] = []
    for p in radius_dir.glob("Week_*"):
        if not p.is_dir():
            continue
        m = WEEK_RE.match(p.name)
        if not m:
            continue
        if int(m.group("R")) != radius:
            continue
        if int(m.group("I")) != I_VALUE:
            continue
        if int(m.group("S")) != SAFE_DISTANCE:
            continue
        if int(m.group("H")) != HORIZON:
            continue
        if (m.group("C") == "True") != fair:
            continue
        matches.append((p, m))

    if not matches:
        raise FileNotFoundError(
            f"No matching Week folder in {radius_dir} for I_{I_VALUE}, "
            f"S_{SAFE_DISTANCE}, H_{HORIZON}, fair={fair}"
        )

    # If reruns exist, prefer the folder whose latest trajectory is newest.
    def score(pm: Tuple[Path, re.Match]) -> float:
        traj = latest_file(pm[0], "vehicles_positions_id_*.json")
        return traj.stat().st_mtime if traj else 0.0

    matches.sort(key=score, reverse=True)
    week_dir, m = matches[0]
    if len(matches) > 1:
        print(f"WARNING: multiple matching Week folders in {radius_dir}; using {week_dir.name}")

    trajectory = latest_file(week_dir, "vehicles_positions_id_*.json")
    if trajectory is None:
        msg = f"No vehicles_positions_id_*.json in {week_dir}"
        if ALLOW_MISSING_TRAJECTORIES:
            print(f"WARNING: {msg}; solver/runtime metrics will still be processed, delay will be blank.")
        else:
            raise FileNotFoundError(msg)

    source_candidates = sorted(radius_dir.glob("RH_1_intesection_possion_discrete_distribution_new*.py"))
    source_code = source_candidates[0] if source_candidates else None

    return RunFiles(
        key=RunKey(case["label"], radius, fair),
        traffic_lambda_x=float(case["lambda_x"]),
        traffic_lambda_y=float(case["lambda_y"]),
        root=root,
        radius_dir=radius_dir,
        week_dir=week_dir,
        trajectory_file=trajectory,
        runtime_file=latest_file(week_dir, "runtime_duration_*"),
        mip_json_file=latest_file(week_dir, "MIP_file-*.json"),
        source_code_file=source_code,
        step_token=m.group("step"),
        safe_distance=int(m.group("S")),
        i_value=int(m.group("I")),
        horizon=int(m.group("H")),
    )


def discover_all_runs() -> Dict[RunKey, RunFiles]:
    runs: Dict[RunKey, RunFiles] = {}
    errors = []
    for case in TRAFFIC_CASES:
        for radius in RADII:
            for fair in (False, True):
                try:
                    rf = discover_one_run(case, radius, fair)
                    runs[rf.key] = rf
                except Exception as exc:
                    errors.append(str(exc))
    expected = len(TRAFFIC_CASES) * len(RADII) * 2
    print(f"Discovered {len(runs)}/{expected} requested MILP runs.")
    if errors:
        for e in errors:
            print("MISSING:", e)
        if REQUIRE_ALL_54_RUN_FOLDERS:
            raise RuntimeError(f"Missing {len(errors)} requested runs; see messages above.")
    return runs


