RE_OPT = re.compile(r"Optimize a model with\s+([\d,]+)\s+rows,\s+([\d,]+)\s+columns\s+and\s+([\d,]+)\s+nonzeros", re.I)
RE_VAR = re.compile(r"Variable types:\s*([\d,]+)\s+continuous,\s*([\d,]+)\s+integer\s*\(([\d,]+)\s+binary\)", re.I)
RE_GEN = re.compile(r"Model has\s+([\d,]+)\s+general constraints", re.I)
RE_PRESOLVED = re.compile(r"Presolved:\s*([\d,]+)\s+rows,\s*([\d,]+)\s+columns,\s*([\d,]+)\s+nonzeros", re.I)
RE_ROOT = re.compile(r"Root relaxation:.*?,\s*([\d,]+)\s+iterations,\s*([0-9.eE+-]+)\s+seconds", re.I)
RE_EXPLORED = re.compile(r"Explored\s+([\d,]+)\s+nodes\s+\(([\d,]+)\s+simplex iterations\)\s+in\s+([0-9.eE+-]+)\s+seconds(?:\s+\(([0-9.eE+-]+)\s+work units\))?", re.I)
RE_BEST = re.compile(r"Best objective\s+([^,]+),\s+best bound\s+([^,]+),\s+gap\s+([^%]+)%", re.I)
RE_MULTI_START = re.compile(r"Multi-objectives:\s*starting optimization with\s+(\d+)\s+objectives", re.I)
RE_MULTI_SOLVED = re.compile(r"Multi-objectives:\s*solved in\s+([0-9.eE+-]+)\s+seconds(?:\s+\(([0-9.eE+-]+)\s+work units\))?", re.I)
RE_THREADS_USED = re.compile(r"Thread count was\s+(\d+)", re.I)


def to_int(s: str) -> int:
    return int(s.replace(",", ""))


def parse_gurobi_log(path: Path) -> dict:
    out = {
        "log_file": str(path),
        "iteration": None,
        "model_rows": None,
        "model_columns": None,
        "model_nonzeros": None,
        "original_continuous_vars": None,
        "original_integer_vars": None,
        "original_binary_vars": None,
        "general_constraints": None,
        "presolved_rows": None,
        "presolved_columns": None,
        "presolved_nonzeros": None,
        "presolved_continuous_vars": None,
        "presolved_integer_vars": None,
        "presolved_binary_vars": None,
        "objective_count": None,
        "root_relaxation_iterations": None,
        "root_relaxation_s": None,
        "nodes": None,
        "simplex_iterations": None,
        "solver_runtime_s": None,
        "solver_work_units": None,
        "best_objective": None,
        "best_bound": None,
        "final_gap_percent": None,
        "threads_used": None,
        "status": "UNKNOWN",
        "parse_error": None,
    }
    mm = LOG_ITER_RE.search(path.name)
    if mm:
        out["iteration"] = int(mm.group(1))

    first_model_seen = False
    initial_var_captured = False
    after_presolved = False

    try:
        with path.open("r", encoding="utf-8", errors="ignore") as f:
            for line in f:
                m = RE_OPT.search(line)
                if m and not first_model_seen:
                    out["model_rows"] = to_int(m.group(1))
                    out["model_columns"] = to_int(m.group(2))
                    out["model_nonzeros"] = to_int(m.group(3))
                    first_model_seen = True
                    continue

                m = RE_VAR.search(line)
                if m:
                    if first_model_seen and not initial_var_captured:
                        out["original_continuous_vars"] = to_int(m.group(1))
                        out["original_integer_vars"] = to_int(m.group(2))
                        out["original_binary_vars"] = to_int(m.group(3))
                        initial_var_captured = True
                    elif after_presolved:
                        out["presolved_continuous_vars"] = to_int(m.group(1))
                        out["presolved_integer_vars"] = to_int(m.group(2))
                        out["presolved_binary_vars"] = to_int(m.group(3))
                        after_presolved = False
                    continue

                m = RE_GEN.search(line)
                if m and out["general_constraints"] is None:
                    out["general_constraints"] = to_int(m.group(1))
                    continue

                m = RE_PRESOLVED.search(line)
                if m:
                    out["presolved_rows"] = to_int(m.group(1))
                    out["presolved_columns"] = to_int(m.group(2))
                    out["presolved_nonzeros"] = to_int(m.group(3))
                    after_presolved = True
                    continue

                m = RE_MULTI_START.search(line)
                if m:
                    out["objective_count"] = int(m.group(1))
                    continue

                m = RE_ROOT.search(line)
                if m:
                    out["root_relaxation_iterations"] = to_int(m.group(1))
                    out["root_relaxation_s"] = float(m.group(2))
                    continue

                m = RE_EXPLORED.search(line)
                if m:
                    out["nodes"] = to_int(m.group(1))
                    out["simplex_iterations"] = to_int(m.group(2))
                    # Keep this as fallback; Multi-objective solved time below is preferred.
                    out["solver_runtime_s"] = float(m.group(3))
                    if m.group(4) is not None:
                        out["solver_work_units"] = float(m.group(4))
                    continue

                m = RE_MULTI_SOLVED.search(line)
                if m:
                    out["solver_runtime_s"] = float(m.group(1))
                    if m.group(2) is not None:
                        out["solver_work_units"] = float(m.group(2))
                    continue

                m = RE_BEST.search(line)
                if m:
                    try:
                        out["best_objective"] = float(m.group(1))
                    except Exception:
                        out["best_objective"] = m.group(1).strip()
                    try:
                        out["best_bound"] = float(m.group(2))
                    except Exception:
                        out["best_bound"] = m.group(2).strip()
                    try:
                        out["final_gap_percent"] = float(m.group(3))
                    except Exception:
                        pass
                    continue

                m = RE_THREADS_USED.search(line)
                if m:
                    out["threads_used"] = int(m.group(1))

                if "Optimal solution found" in line:
                    out["status"] = "OPTIMAL"
                elif "Time limit reached" in line:
                    out["status"] = "TIME_LIMIT"
                elif "Model is infeasible" in line or "Infeasible model" in line:
                    out["status"] = "INFEASIBLE"
                elif "Sub-optimal termination" in line:
                    out["status"] = "SUBOPTIMAL"
    except Exception as exc:
        out["parse_error"] = str(exc)
    return out


