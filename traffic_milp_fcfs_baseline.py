def collect_gurobi_logs(folder: Path) -> List[Path]:
    # Deduplicate by optimization iteration, retaining newest file if rerun.
    by_it: Dict[int, Tuple[float, Path]] = {}
    with os.scandir(folder) as it:
        for ent in it:
            if not ent.is_file() or not ent.name.startswith("gurobi_") or not ent.name.endswith(".log"):
                continue
            m = LOG_ITER_RE.search(ent.name)
            if not m:
                continue
            k = int(m.group(1))
            mt = ent.stat().st_mtime
            old = by_it.get(k)
            p = Path(ent.path)
            if old is None or mt > old[0]:
                by_it[k] = (mt, p)
    return [by_it[k][1] for k in sorted(by_it)]


def solver_cache_paths(rf: RunFiles) -> Tuple[Path, Path]:
    d = OUTPUT_ROOT / "solver_detail" / rf.key.traffic_label / ("fair" if rf.key.fair else "nofair")
    return d / f"R_{rf.key.radius}_solver_iterations.csv.gz", d / f"R_{rf.key.radius}_solver_summary.json"


def logs_signature(logs: Sequence[Path]) -> dict:
    if not logs:
        return {"count": 0, "max_mtime": None, "sum_size": 0}
    count = len(logs)
    max_mtime = 0.0
    sum_size = 0
    for p in logs:
        st = p.stat()
        max_mtime = max(max_mtime, st.st_mtime)
        sum_size += st.st_size
    return {"count": count, "max_mtime": max_mtime, "sum_size": sum_size}


def summarize_solver_values(values: Dict[str, List[float]], status_counts: Dict[str, int], log_count: int, parse_error_count: int) -> dict:
    out = {
        "solver_log_count": log_count,
        "solver_parse_error_count": parse_error_count,
    }
    for key in AGG_KEYS:
        s = stats(values.get(key, []))
        for stat_name in ("mean", "median", "p95", "max", "min", "total"):
            out[f"{key}_{stat_name}"] = s[stat_name]
    for status in ("OPTIMAL", "TIME_LIMIT", "INFEASIBLE", "SUBOPTIMAL", "UNKNOWN"):
        out[f"status_{status}_count"] = int(status_counts.get(status, 0))
    return out


def parse_solver_run(rf: RunFiles) -> dict:
    logs = collect_gurobi_logs(rf.week_dir)
    sig = logs_signature(logs)
    detail_path, summary_path = solver_cache_paths(rf)
    detail_path.parent.mkdir(parents=True, exist_ok=True)

    if USE_SOLVER_CACHE and summary_path.exists() and detail_path.exists():
        try:
            cached = json.loads(summary_path.read_text(encoding="utf-8"))
            if cached.get("log_signature") == sig:
                result = cached["summary"]
                result["solver_cache_used"] = True
                result["solver_detail_file"] = str(detail_path)
                return result
        except Exception:
            pass

    print(f"    parsing {len(logs)} Gurobi logs with {LOG_WORKERS} workers")
    values: Dict[str, List[float]] = {k: [] for k in AGG_KEYS}
    status_counts: Dict[str, int] = {}
    parse_errors = 0
    t0 = time.perf_counter()

    with gzip.open(detail_path, "wt", newline="", encoding="utf-8") as gf:
        writer = csv.DictWriter(gf, fieldnames=SOLVER_DETAIL_FIELDS, extrasaction="ignore")
        writer.writeheader()
        if LOG_WORKERS > 1 and len(logs) > 1:
            with ThreadPoolExecutor(max_workers=LOG_WORKERS) as ex:
                iterator = ex.map(parse_gurobi_log, logs)
                for idx, row in enumerate(iterator, start=1):
                    writer.writerow(row)
                    for key in AGG_KEYS:
                        v = row.get(key)
                        if isinstance(v, (int, float)) and math.isfinite(float(v)):
                            values[key].append(float(v))
                    st = str(row.get("status", "UNKNOWN"))
                    status_counts[st] = status_counts.get(st, 0) + 1
                    if row.get("parse_error"):
                        parse_errors += 1
                    if idx % 5000 == 0:
                        print(f"      parsed {idx}/{len(logs)} logs")
        else:
            for idx, p in enumerate(logs, start=1):
                row = parse_gurobi_log(p)
                writer.writerow(row)
                for key in AGG_KEYS:
                    v = row.get(key)
                    if isinstance(v, (int, float)) and math.isfinite(float(v)):
                        values[key].append(float(v))
                st = str(row.get("status", "UNKNOWN"))
                status_counts[st] = status_counts.get(st, 0) + 1
                if row.get("parse_error"):
                    parse_errors += 1
                if idx % 5000 == 0:
                    print(f"      parsed {idx}/{len(logs)} logs")

    summary = summarize_solver_values(values, status_counts, len(logs), parse_errors)
    summary.update({
        "solver_log_parse_wall_s": time.perf_counter() - t0,
        "solver_cache_used": False,
        "solver_detail_file": str(detail_path),
    })
    if USE_SOLVER_CACHE:
        summary_path.write_text(
            json.dumps({"log_signature": sig, "summary": summary}, indent=2, allow_nan=False),
            encoding="utf-8",
        )
    return summary


