def run_event_fcfs(arrivals: Sequence[dict], lambda_x: float, lambda_y: float) -> Tuple[List[dict], dict]:
    t0 = time.perf_counter()
    ordered = sorted(arrivals, key=lambda r: int(r["uid"]))
    same_gap = D_SAFE / V_NOMINAL
    cross_gap = D_SEP / V_NOMINAL

    rows: List[dict] = []
    prev_service: Optional[float] = None
    prev_axis: Optional[str] = None
    transition_gaps: List[float] = []
    same_count = 0
    cross_count = 0

    for rank, arr in enumerate(ordered, start=1):
        release = float(arr["release_time_s"])
        axis = str(arr["axis"])
        if prev_service is None:
            service = release
            applied_gap = None
        else:
            applied_gap = same_gap if axis == prev_axis else cross_gap
            service = max(release, prev_service + applied_gap)
            transition_gaps.append(applied_gap)
            if axis == prev_axis:
                same_count += 1
            else:
                cross_count += 1
        wait = max(0.0, service - release)
        rows.append({
            "uid": int(arr["uid"]),
            "axis": axis,
            "arrival_rank": rank,
            "release_time_s": release,
            "scheduled_center_time_s": service,
            "applied_service_gap_s": applied_gap,
            "virtual_wait_delay_s": wait,
        })
        prev_service = service
        prev_axis = axis

    waits = [r["virtual_wait_delay_s"] for r in rows]
    ws = stats(waits)

    releases = [r["release_time_s"] for r in rows]
    lam_emp = None
    if len(releases) >= 2 and max(releases) > min(releases):
        lam_emp = (len(releases) - 1) / (max(releases) - min(releases))

    # Empirical transition-based M/G/1 approximation.
    empirical_es = statistics.fmean(transition_gaps) if transition_gaps else None
    empirical_es2 = statistics.fmean([g * g for g in transition_gaps]) if transition_gaps else None
    empirical_rho = None
    empirical_mg1 = None
    if lam_emp is not None and empirical_es is not None and empirical_es2 is not None:
        empirical_rho = lam_emp * empirical_es
        empirical_mg1 = (
            lam_emp * empirical_es2 / (2.0 * (1.0 - empirical_rho))
            if empirical_rho < 1.0 else math.inf
        )

    # Configured-rate theoretical approximation for two independent streams.
    lam_cfg = lambda_x + lambda_y
    px = lambda_x / lam_cfg if lam_cfg > 0 else 0.0
    py = lambda_y / lam_cfg if lam_cfg > 0 else 0.0
    p_same = px * px + py * py
    p_cross = 1.0 - p_same
    cfg_es = p_same * same_gap + p_cross * cross_gap
    cfg_es2 = p_same * same_gap**2 + p_cross * cross_gap**2
    cfg_rho = lam_cfg * cfg_es
    cfg_mg1 = lam_cfg * cfg_es2 / (2.0 * (1.0 - cfg_rho)) if cfg_rho < 1.0 else math.inf

    summary = {
        "method": "FCFS_EVENT_VIRTUAL_WAIT_RADIUS_INDEPENDENT",
        "agent_count": len(rows),
        "ordering": "ascending global UID",
        "same_flow_service_gap_s": same_gap,
        "cross_flow_service_gap_s": cross_gap,
        "mean_delay_s": ws["mean"],
        "median_delay_s": ws["median"],
        "std_delay_s": ws["std"],
        "p95_delay_s": ws["p95"],
        "max_delay_s": ws["max"],
        "total_delay_s": ws["total"],
        "same_transition_count": same_count,
        "cross_transition_count": cross_count,
        "empirical_lambda_total_veh_s": lam_emp,
        "empirical_mean_service_gap_s": empirical_es,
        "empirical_rho": empirical_rho,
        "empirical_mg1_mean_wait_s": empirical_mg1,
        "configured_lambda_x_veh_s": lambda_x,
        "configured_lambda_y_veh_s": lambda_y,
        "configured_lambda_total_veh_s": lam_cfg,
        "theoretical_p_same": p_same,
        "theoretical_p_cross": p_cross,
        "theoretical_mean_service_gap_s": cfg_es,
        "theoretical_rho": cfg_rho,
        "theoretical_mg1_mean_wait_s": cfg_mg1,
        "fcfs_compute_wall_s": time.perf_counter() - t0,
        "fcfs_complexity": "O(N) time, O(N) output storage, no mathematical-program solver",
        "note": (
            "The M/G/1 values are analytical approximations. The exact finite-sample FCFS "
            "value is computed directly from the common UID arrival sequence above."
        ),
    }
    return rows, summary


