#!/usr/bin/env python3
"""
MILP / FCFS Post-Processing for Autonomous Intersection Experiments
===================================================================

This script post-processes the simulation results used in the thesis study
of early versus late centralized intervention at a signal-less orthogonal
intersection.

Purpose
-------
The script performs two related analyses:

1. It extracts trajectory, MILP model-size, Gurobi runtime, MIP-gap, and
   full-run timing statistics from the existing simulation experiments.

2. It constructs an idealized First-Come, First-Served (FCFS) scheduling
   baseline for comparison with the trajectory-based MILP controller.

The FCFS benchmark is NOT a dynamically simulated vehicle controller.
It is a radius-independent event-based scheduling reference that preserves
the generated agent arrival order and assigns virtual intersection service
times using fixed same-flow and cross-flow separation headways.

FCFS formulation
----------------
Agents are processed in their generated arrival order. In these simulations,
the global UID is assigned according to that generation order and is therefore
used as the FCFS ordering key.

For agent k, let:

    A_k = nominal arrival/release time,
    T_k = scheduled FCFS service time.

The required service headway is

    h_same  = d_safe / V_nominal
            = 3 / 15
            = 0.2 s

for consecutive agents from the same flow, and

    h_cross = d_sep / V_nominal
            = 4 / 15
            ≈ 0.2667 s

for consecutive agents from conflicting flows.

The event-based FCFS schedule is

    T_1 = A_1

    T_k = max(A_k, T_{k-1} + h_k)

and the corresponding virtual scheduling delay is

    D_k^FCFS = T_k - A_k.

Therefore, the FCFS result represents scheduling delay only. It does not
represent a physical stop, acceleration maneuver, or dynamically simulated
trajectory, and no velocity-adjustment metric is assigned to the FCFS
benchmark.

Radius independence
-------------------
Only one FCFS benchmark is generated for each traffic realization
(lambda_x = lambda_y = 0.9, 0.7, or 0.5 s^-1). The FCFS value is independent
of control-zone radius R and is used as a common arrival-order reference for
all MILP radii at the same traffic density.

Common evaluation population
----------------------------
The simulations use a finite arrival-generation window. Consequently, some
late-generated agents may not complete their full control-zone traversal in
every simulation.

For each traffic density, the script therefore identifies the largest
consecutive global-UID prefix that has a complete trajectory in every
AVAILABLE trajectory file used for comparison. The same common population is
then used for the MILP delay and FCFS calculations.

If a trajectory JSON is missing for a run, that run is excluded only from
trajectory-delay/common-population calculations. Its Gurobi model-size,
solver-runtime, MIP-gap, and available wall-clock statistics are still
retained. No missing trajectory delay is imputed.

MILP delay
----------
For each completed MILP trajectory, the script determines the time at which
the agent crosses the -R and +R control-zone boundaries using linear
interpolation between simulation samples.

The trajectory-based delay is

    delay_q(R)
        = [t_exit,q(R) - t_entry,q(R)]
          - 2R / V_nominal.

This is evaluated over the same common agent population used for the FCFS
comparison.

Computational analysis
----------------------
The script parses the individual Gurobi log files generated by the
receding-horizon MILP simulations and records, among other quantities:

    - original model rows and columns,
    - continuous, integer, and binary variable counts,
    - presolved model dimensions,
    - number of general constraints,
    - solver runtime,
    - branch-and-bound nodes,
    - simplex iterations,
    - final MIP gap,
    - solver termination status.

Per-solve Gurobi runtime is kept separate from the complete program
wall-clock duration. When both are available, their difference represents
aggregate non-solver overhead, including model construction, constraint
generation, Python-side simulation operations, state updates, data handling,
and file I/O.

Traffic cases
-------------
The script processes three equal per-flow arrival rates:

    lambda_x = lambda_y = 0.9 s^-1
    lambda_x = lambda_y = 0.7 s^-1
    lambda_x = lambda_y = 0.5 s^-1

For each density, the following control-zone radii are analyzed:

    R = 40, 60, 80, 100, 120, 140, 160, 180, 200 m

and both controller configurations are considered:

    fair = False
    fair = True

This gives 3 x 9 x 2 = 54 requested MILP experiment folders.

Important note on the high-density fairness case
------------------------------------------------
The fairness-enabled R = 40 m simulation for
lambda_x = lambda_y = 0.9 s^-1 did not produce a complete trajectory file.
Its trajectory-derived delay is therefore left blank. Available Gurobi
statistics recorded before termination are retained.

Analytical FCFS approximation
-----------------------------
The script additionally reports empirical and configured-rate M/G/1 waiting
time approximations. These quantities are supplementary analytical references.

The finite-sample FCFS benchmark used in the MILP comparison is the direct
event-based recursion described above, not the M/G/1 approximation.

Main outputs
------------
Results are written under:

    /ibex/user/ghoriss/FCFS_MILP_postprocess_seed20/

Important summary files include:

    paper_summary.csv
        One row for each MILP traffic/radius/fairness configuration.

    paper_comparison_wide.csv
        Fairness-disabled and fairness-enabled MILP results presented
        side-by-side together with the traffic-matched FCFS reference.

    fcfs_summary.csv
        One radius-independent FCFS result for each traffic density.

    common_population_summary.csv
        Common evaluation population and trajectory-availability checks.

    experiment_inventory.csv
        Paths, configuration information, and available source files for
        each experiment.

    parameters.csv
        Parameters used by the post-processing analysis.

Detailed per-agent FCFS results, MILP delays, and per-solve Gurobi
statistics are also written to the corresponding per-traffic directories.

Reproducibility and data handling
---------------------------------
The script is read-only with respect to the original simulation experiment
directories. It creates only post-processing outputs and cache files under
OUTPUT_ROOT.

The study uses one fixed traffic realization (seed = 20) for each traffic
density. Consequently, reported percentiles characterize variation within
that realization and should not be interpreted as confidence intervals over
independent traffic realizations.

Author
------
Salman Ghori

Research context
----------------
PhD research on early versus late traffic management for autonomous agents,
including efficiency, crossing-order fairness, and computational scaling of
receding-horizon MILP coordination.
"""

